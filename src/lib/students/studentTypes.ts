/**
 * Students — wire shape of Muntajir's REAL Student Core API
 * (feature/student-core; runtime schema at backend 95a147f is
 * authoritative — docs/openapi.yaml has known discrepancies). snake_case,
 * same conventions as every other ERP service. studentsApi.ts's
 * fromWire()/studentFormMapping.ts's formDataToStudentBody() are the only
 * places this shape meets the network.
 *
 * Nullability: required-at-final-save fields (first_name, gender,
 * date_of_birth, home_address, ...) are typed non-nullable because
 * fromWire() normalizes a draft's missing values to ""/defaults — a draft
 * legitimately has them empty mid-fill. The OUTBOUND body
 * (StudentWriteBody) is the honest one: null for anything not filled yet.
 *
 * UI-ONLY fields (academic_house_id, boarding_house_id, agent_id,
 * extra_curricular_ids, fee_display) are NOT part of the confirmed wire
 * schema — the backend 422s on academic_house_id/agent_id/
 * extra_curricular_ids unless null/omitted. They stay on this type only so
 * the existing UI that renders them keeps compiling; fromWire() reads them
 * tolerantly if a response ever carries them, and formDataToStudentBody()
 * NEVER sends them.
 */

/**
 * "withdrawn" | "suspended" | "expelled" share one admin flow (a single
 * form: pick the category + reason + date) and all land on the Students
 * list's "Withdrawn" tab, distinguished there by a Status column — see
 * StudentsScreen.tsx. "draft" is wizard-only (Save Draft, not yet a real
 * student). "inactive" exists in the type but isn't surfaced by any tab
 * yet — reserved, not actively used by Student List/Withdrawn/Graduate.
 */
export type StudentStatus = "active" | "graduated" | "withdrawn" | "suspended" | "expelled" | "draft" | "inactive";
export type StudentGender = "male" | "female";
export type StudentMode = "day" | "boarding";
export type RelationshipType = "parent" | "guardian";

export type PersonBlock = {
  first_name: string;
  middle_name: string | null;
  last_name: string;
  phone: string;
  email: string | null;
  occupation: string | null;
};

export type AddressBlock = {
  street: string;
  country_code: string | null;
  state_code: string | null;
  city: string | null;
  postal_code: string | null;
  /** Free text, no dataset backs it (no public/data/lga/*.json). Flagged to reconcile with Muntajir — may become a structured per-state dataset later. */
  lga_or_area: string | null;
};

export type EmergencyContact = { name: string | null; phone: string | null };

export type PastRecord = {
  /** React key / delete handle only. Taken from the response if the backend returns one per record (unconfirmed), else generated by fromWire() — never sent. */
  id: string;
  school: string | null;
  class: string | null;
  grade: string | null;
  rank: string | null;
  /** Free text per spec ("Year (text)"), not a date. */
  year: string | null;
  attachment_file_id: string | null;
};

/** Mock referral agent — Step 5. */
export type Agent = { id: string; name: string; agency: string | null };

export type Student = {
  /** Student UUID — what every /erp/students/:id route takes. */
  id: string;
  /** Server-assigned DISPLAY id (e.g. "STU0042"). Read-only — NEVER generated frontend-side. Null on drafts until submit (assumed — reconcile on staging). */
  student_id: string | null;
  status: StudentStatus;
  /** Draft-resume cursor (1|2|3) returned by GET — the wizard step the draft was last saved from (sent as current_step on draft saves). Null once status leaves "draft". */
  draft_last_step: number | null;
  /** Sent from the session's selected year on every save (backend can also infer it from class_id). */
  academic_year_id: string | null;

  // --- Step 1: Class Details ---
  school_type_id: string;
  class_id: string;
  class_arm_id: string;
  /** Nullable: a class may have no terms configured yet. */
  class_term_id: string | null;
  /** UI-ONLY — Academic House is out of scope backend-side (422 if sent). */
  academic_house_id: string | null;
  /** UI-ONLY — not in the confirmed schema. Only meaningful for mode:"boarding" students. Distinct from academic_house_id (inter-house competitions), this is which dormitory/hostel a boarder lives in. */
  boarding_house_id: string | null;
  mode: StudentMode;
  /** UI-ONLY — must be empty/omitted on the wire (422 otherwise). */
  extra_curricular_ids: string[];
  /** UI-ONLY — display-only "—", pending the Fees/Accounts module. */
  fee_display: string | null;

  // --- Step 2: Student Details ---
  photo_file_id: string | null;
  first_name: string;
  /** "Other Names" in the UI — any middle name(s) collectively, same convention as Nigerian school admission forms. */
  other_names: string | null;
  last_name: string;
  /** Separate from student_id, editable, optional — blank on a final save makes the backend default it to student_id. */
  admission_number: string | null;
  /** Optional on drafts; REQUIRED on final create/submit/active update. */
  email: string | null;
  gender: StudentGender;
  /** Dropdown value, or the free-text "Other" value when religion_is_other is true. */
  religion: string | null;
  religion_is_other: boolean;
  nationality: string;
  /** ISO date; age is always computed client-side at render time, never stored. */
  date_of_birth: string;
  height: string | null;
  weight: string | null;
  blood_group: string | null;
  genotype: string | null;
  allergies: string | null;
  medical_conditions: string | null;
  medications: string | null;
  special_needs_notes: string | null;

  // --- Step 3: Parent/Guardian ---
  relationship_type: RelationshipType;
  father: PersonBlock | null; // relationship_type === "parent" only
  mother: PersonBlock | null; // relationship_type === "parent" only
  guardian: PersonBlock | null; // relationship_type === "guardian" only
  /** Which entered block is the primary contact. Flagged to reconcile with Muntajir — frontend-chosen name/enum, unconfirmed with backend. */
  primary_contact: "father" | "mother" | "guardian" | null;

  // --- Step 4: Address ---
  home_address: AddressBlock;
  other_address_same_as_home: boolean;
  /** Null when other_address_same_as_home is true — don't duplicate data. */
  other_address: AddressBlock | null;
  /** 0–2 entries, each optional as a whole. */
  emergency_contacts: EmergencyContact[];

  // --- Step 5: Agent (all optional) ---
  /** UI-ONLY — agents aren't supported backend-side yet (422 if sent). has_agent_commission IS supported. */
  agent_id: string | null;
  has_agent_commission: boolean;

  // --- Step 6: Siblings ---
  sibling_student_ids: string[];

  // --- Step 7: Past Records ---
  past_records: PastRecord[];

  // --- Login Details ---
  /** 1–100 chars, no whitespace, case preserved. Blank/omitted on a final save -> backend defaults it to the lowercased email. The initial password is backend-assigned (forced change at first login) — there is no password field on the wire. */
  username: string;
  /** Flag-only backend-side for now. */
  two_factor_enabled: boolean;
  /** false -> the student's user is deactivated and their sessions revoked. */
  login_activated: boolean;

  created_at: string;
  updated_at: string;
};

/** Outbound PersonBlock — every field nullable, since a draft can carry a partly-filled block. */
export type PersonBlockBody = { [K in keyof PersonBlock]: string | null };
export type AddressBlockBody = { [K in keyof AddressBlock]: string | null };
export type PastRecordBody = Omit<PastRecord, "id">;

/**
 * Request body for POST /drafts, PUT /:id/draft, POST /:id/submit, POST
 * /students and PUT /:id — the COMPLETE accumulated form every time
 * (never a partial patch). current_step is added by studentsApi.ts for the
 * two draft routes only. `username` is omitted (not null) when blank, so
 * a final save gets the email default and an update preserves the
 * existing one.
 */
export type StudentWriteBody = {
  mode: StudentMode | null;
  first_name: string | null;
  other_names: string | null;
  last_name: string | null;
  gender: StudentGender | null;
  religion: string | null;
  religion_is_other: boolean;
  nationality: string | null;
  date_of_birth: string | null;
  height: string | null;
  weight: string | null;
  blood_group: string | null;
  genotype: string | null;
  allergies: string | null;
  medical_conditions: string | null;
  medications: string | null;
  special_needs_notes: string | null;
  photo_file_id: string | null;
  admission_number: string | null;

  email: string | null;
  username?: string;
  login_activated: boolean;
  two_factor_enabled: boolean;

  relationship_type: RelationshipType;
  father: PersonBlockBody | null;
  mother: PersonBlockBody | null;
  guardian: PersonBlockBody | null;
  primary_contact: "father" | "mother" | "guardian" | null;

  home_address: AddressBlockBody | null;
  other_address_same_as_home: boolean;
  other_address: AddressBlockBody | null;

  emergency_contacts: EmergencyContact[];
  sibling_student_ids: string[];
  past_records: PastRecordBody[];

  academic_year_id: string | null;
  school_type_id: string | null;
  class_id: string | null;
  class_arm_id: string | null;
  class_term_id: string | null;

  has_agent_commission: boolean;
};

/** One route per action: POST /erp/students/:id/{action}. */
export type StudentStatusAction = "withdraw" | "suspend" | "expel" | "reactivate" | "graduate" | "restore";

/**
 * Per-action bodies, exactly as the backend validates them. reason is
 * 1–500 chars where present; effective_on is YYYY-MM-DD. Graduate REJECTS
 * reason — the type makes sending one impossible.
 */
export type StudentStatusBodies = {
  withdraw: { reason?: string; effective_on?: string };
  suspend: { reason: string; effective_on?: string };
  expel: { reason: string; effective_on?: string };
  reactivate: { reason: string; effective_on?: string };
  graduate: { effective_on?: string };
  restore: { reason?: string; effective_on?: string };
};

/**
 * GET /erp/students/:id/status-events item. FLAGGED, UNCONFIRMED shape —
 * fromStatusEventWire() reads it tolerantly; reconcile on staging.
 */
export type StudentStatusEvent = {
  id: string;
  action: string | null;
  from_status: string | null;
  to_status: string | null;
  reason: string | null;
  effective_on: string | null;
  created_at: string | null;
  /** Display name of whoever made the change, if the backend includes one. */
  actor_name: string | null;
};
